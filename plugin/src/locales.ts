export type Translator = (key: string, values?: Record<string, string | number>) => string;
export function resolveLanguage(language = 'en'): 'en' | 'zh' {
  return /^zh(?:-[a-z0-9]+)*$/i.test(language) ? 'zh' : 'en';
}
/** Single-pass substitution does not interpret placeholders inside user titles. */
export function createTranslator(language = 'en'): Translator {
  const dictionary: Record<string, string> = resolveLanguage(language) === 'zh' ? zh : en;
  return (key, values = {}) => (dictionary[key] ?? (en as Record<string, string>)[key] ?? key)
    .replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder));
}
