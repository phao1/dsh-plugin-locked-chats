import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {build} from 'esbuild';
import {SlotCore} from '@deepseek-ai/dsh-client-ui-slots';

test('native picker keeps locale, directory flow and owner actions while filtering locked workspace names',async t=>{
  const dir=mkdtempSync(join(tmpdir(),'dsh-picker-test-')),outfile=join(dir,'component.mjs');
  t.after(()=>rmSync(dir,{recursive:true}));
  const pluginRoot=fileURLToPath(new URL('../',import.meta.url));
  await build({stdin:{contents:`export {composeWorkspacePicker} from './client/workspace-picker.mjs';export {createElement} from 'react';export {renderToStaticMarkup} from 'react-dom/server.browser';`,resolveDir:pluginRoot},bundle:true,platform:'node',format:'esm',outfile,alias:{react:resolve(pluginRoot,'node_modules/react')}});
  const {createElement:h,renderToStaticMarkup,composeWorkspacePicker}=await import(pathToFileURL(outfile).href);
  const slots=new SlotCore(),register=slots.register.bind(slots) as Function;
  register({name:'root',children:{'conversation.hero.workspace':{kind:'single',scope:'root'},'locked-chats.vault-workspace':{kind:'single',scope:'root'},'locked-chats.lock-workspace':{kind:'single',scope:'root'}}},()=>null);
  let rendered:any;
  const native=(props:any)=>{rendered=props;return h('div',null,
    props.useWorkspaces((state:any)=>state.items).map((item:any)=>h('button',{key:item.workspaceId},item.title)),
    props.renderSlot('conversation.hero.workspace.directoryFlow',{}));};
  const inject=()=>({createWorkspace:()=>{}}),flow=()=>null;
  register({name:'conversation.hero.workspace',inject,locale:'workspace',children:{'conversation.hero.workspace.directoryFlow':{kind:'single',scope:'root'}}},native);
  register({name:'conversation.hero.workspace.directoryFlow'},flow);
  const original=slots.entries('conversation.hero.workspace')[0];
  const client:any={state:{ready:true,workspaceIds:['locked']},subscribe:()=>()=>{},getSnapshot:()=>client.state};
  const stop=composeWorkspacePicker(slots,client);await Promise.resolve();
  const composed=slots.entriesOfSlot('conversation.hero.workspace')[0]!;
  assert.equal(composed.inject,inject);assert.equal(composed.locale,'workspace');
  assert.ok(slots.entries('conversation.hero.workspace').includes(original!));
  const snapshot={phase:'ready',items:[{workspaceId:'normal',title:'Visible workspace'},{workspaceId:'locked',title:'Secret title'}]};
  const picks:string[]=[],closed:string[]=[];
  const props={open:true,selectedId:'normal',useWorkspaces:(selector:Function)=>selector(snapshot),onPick:(id:string)=>picks.push(id),onClose:()=>closed.push('close'),renderSlot:(key:string)=>key};
  const html=renderToStaticMarkup(h(composed.component as any,props));
  assert.match(html,/Visible workspace/);assert.doesNotMatch(html,/Secret title/);
  assert.match(html,/locked-chats\.picker\.conversation\.hero\.workspace\.directoryFlow/);
  assert.equal(rendered.selectedId,'normal');assert.equal(rendered.open,true);assert.equal(snapshot.items.length,2);
  rendered.onPick('normal');rendered.onPick('locked');
  assert.deepEqual(picks,['normal']);assert.deepEqual(closed,['close']);
  const mirrored=slots.entriesOfSlot('locked-chats.picker.conversation.hero.workspace.directoryFlow');
  assert.equal(mirrored.length,1);
  const stopVault=composeWorkspacePicker(slots,client,{target:'locked-chats.vault-workspace',vault:true});await Promise.resolve();
  const vault=slots.entriesOfSlot('locked-chats.vault-workspace')[0]!;
  client.state={ready:true,unlocked:true,workspaceIds:['locked']};
  const vaultHtml=renderToStaticMarkup(h(vault.component as any,props));
  assert.match(vaultHtml,/Visible workspace/);assert.match(vaultHtml,/Secret title/);
  assert.match(vaultHtml,/locked-chats\.vault-picker\.conversation\.hero\.workspace\.directoryFlow/);
  rendered.onPick('locked');assert.deepEqual(picks,['normal','locked']);
  client.state={ready:true,unlocked:false,workspaceIds:['locked']};
  const closedVault=renderToStaticMarkup(h(vault.component as any,props));
  assert.doesNotMatch(closedVault,/Visible workspace|Secret title/);
  rendered.onPick('locked');assert.deepEqual(picks,['normal','locked']);
  client.state={ready:true,unlocked:true,workspaceIds:['locked']};
  const stopLock=composeWorkspacePicker(slots,client,{target:'locked-chats.lock-workspace',vault:true,lockSelection:true});await Promise.resolve();
  const lockPicker=slots.entriesOfSlot('locked-chats.lock-workspace')[0]!;
  const lockHtml=renderToStaticMarkup(h(lockPicker.component as any,props));
  assert.match(lockHtml,/Visible workspace/);assert.doesNotMatch(lockHtml,/Secret title/);
  assert.equal(rendered.useDirectoryFlow((value:boolean)=>value),false);
  rendered.onPick('locked');assert.deepEqual(picks,['normal','locked']);
  stopLock();await Promise.resolve();
  stopVault();await Promise.resolve();
  client.state={ready:false,workspaceIds:[]};
  const pending=renderToStaticMarkup(h(composed.component as any,props));
  assert.doesNotMatch(pending,/Visible workspace|Secret title/);
  stop();await Promise.resolve();
  assert.equal(slots.entriesOfSlot('conversation.hero.workspace')[0],original);
  assert.equal(slots.entriesOfSlot('conversation.hero.workspace.directoryFlow')[0]?.component,flow);
  assert.equal(slots.entriesOfSlot('locked-chats.picker.conversation.hero.workspace.directoryFlow').length,0);
});
